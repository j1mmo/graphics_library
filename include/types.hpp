#ifndef TYPES_HPP
#define TYPES_HPP
#pragma once

#include <cstdint>

// Aliases for common integer types
using uint   = unsigned int;
using ulong  = unsigned long;
using uchar  = unsigned char;
using ushort = unsigned short;

// Aliases for fixed-width integer types
using u8  = uint8_t;
using u16 = uint16_t;
using u32 = uint32_t;
using u64 = uint64_t;

using i8  = int8_t;
using i16 = int16_t;
using i32 = int32_t;
using i64 = int64_t;

// Optional: floating point aliases
using f32 = float;
using f64 = double;

#endif //TYPES_HPP
